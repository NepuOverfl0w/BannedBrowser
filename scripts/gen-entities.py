#!/usr/bin/env python3
"""Regenerate crates/bb-html/src/entities.rs from third_party/entities.json
(https://html.spec.whatwg.org/entities.json)."""
import json, os
root = os.path.join(os.path.dirname(__file__), "..")
data = json.load(open(os.path.join(root, "third_party", "entities.json")))
items = sorted((k[1:], v["characters"]) for k, v in data.items())
def esc(s):
    return "".join("\\u{%x}" % ord(c) if ord(c) < 0x20 or ord(c) > 0x7e or c in '"\\' else c for c in s)
out = ["// @generated by scripts/gen-entities.py from the WHATWG entities.json. Do not edit.",
       "//! HTML §13.5 named character references, sorted by name (without the leading `&`).",
       "",
       f"pub(crate) static ENTITIES: [(&str, &str); {len(items)}] = ["]
for name, chars in items:
    out.append(f'    ("{name}", "{esc(chars)}"),')
out.append("];")
open(os.path.join(root, "crates", "bb-html", "src", "entities.rs"), "w").write("\n".join(out) + "\n")
print(len(items), "entities")
