#!/usr/bin/env python3
"""Generate crates/bb-url/src/idna_data.txt from Unicode data files.

Usage: scripts/gen-idna.py [DIR]

DIR holds IdnaMappingTable.txt (https://www.unicode.org/Public/idna/latest/) and
DerivedJoiningType.txt and DerivedGeneralCategory.txt
(https://www.unicode.org/Public/UCD/latest/ucd/extracted/); without DIR they are downloaded.
The output keeps the data unchanged, re-encoded compactly:

  T <start> <end> <status> [<mapping code points>]   UTS #46 mapping table ranges
      status: v valid, i ignored, m mapped, d deviation, x disallowed
  J <start> <end> <joining type>                     L, D, R or T (others are U)
  M <start> <end>                                    General_Category Mark (Mn, Mc, Me)

All numbers are hexadecimal.
"""

import os
import sys
import urllib.request

FILES = {
    "IdnaMappingTable.txt": "https://www.unicode.org/Public/idna/latest/IdnaMappingTable.txt",
    "DerivedJoiningType.txt": "https://www.unicode.org/Public/UCD/latest/ucd/extracted/DerivedJoiningType.txt",
    "DerivedGeneralCategory.txt": "https://www.unicode.org/Public/UCD/latest/ucd/extracted/DerivedGeneralCategory.txt",
}

STATUS = {"valid": "v", "ignored": "i", "mapped": "m", "deviation": "d", "disallowed": "x"}


def read(dirname, name):
    if dirname:
        with open(os.path.join(dirname, name), encoding="utf-8") as f:
            return f.read()
    with urllib.request.urlopen(FILES[name]) as r:
        return r.read().decode("utf-8")


def rows(text):
    for line in text.splitlines():
        line = line.split("#", 1)[0].strip()
        if not line:
            continue
        yield [f.strip() for f in line.split(";")]


def span(field):
    a, _, b = field.partition("..")
    return int(a, 16), int(b or a, 16)


def version(text):
    for line in text.splitlines()[:12]:
        if "Version:" in line or line.startswith("# Derived"):
            return line.lstrip("# ").strip()
    return "unknown version"


def main():
    dirname = sys.argv[1] if len(sys.argv) > 1 else None
    table = read(dirname, "IdnaMappingTable.txt")
    joining = read(dirname, "DerivedJoiningType.txt")
    gc = read(dirname, "DerivedGeneralCategory.txt")
    out = [
        "# UTS #46 IDNA data for bb-url, generated by scripts/gen-idna.py; do not edit.",
        f"# From IdnaMappingTable.txt ({version(table)}), {version(joining)}, {version(gc)}.",
        "# Unicode data, (c) Unicode, Inc., https://www.unicode.org/terms_of_use.html",
    ]
    # The mapping table, merging adjacent ranges of the same unmapped status.
    merged = []
    for f in rows(table):
        a, b = span(f[0])
        st = STATUS[f[1]]
        mapping = f[2] if len(f) > 2 and st in "md" else ""
        if st == "d" and not mapping:
            mapping = ""
        if merged and not mapping and not merged[-1][3] and merged[-1][2] == st and merged[-1][1] + 1 == a:
            merged[-1][1] = b
        else:
            merged.append([a, b, st, mapping])
    for a, b, st, mapping in merged:
        line = f"T {a:x} {b:x} {st}"
        if mapping:
            line += " " + " ".join(f"{int(c, 16):x}" for c in mapping.split())
        out.append(line)
    for f in rows(joining):
        if f[1] in ("L", "D", "R", "T"):
            a, b = span(f[0])
            out.append(f"J {a:x} {b:x} {f[1]}")
    marks = []
    for f in rows(gc):
        if f[1] in ("Mn", "Mc", "Me"):
            marks.append(span(f[0]))
    marks.sort()
    joined = []
    for a, b in marks:
        if joined and joined[-1][1] + 1 == a:
            joined[-1][1] = b
        else:
            joined.append([a, b])
    for a, b in joined:
        out.append(f"M {a:x} {b:x}")
    dest = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "bb-url", "src", "idna_data.txt")
    with open(dest, "w", encoding="utf-8") as f:
        f.write("\n".join(out) + "\n")
    print(f"wrote {dest}: {len(out)} lines")


if __name__ == "__main__":
    main()
